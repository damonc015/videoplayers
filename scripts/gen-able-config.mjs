#!/usr/bin/env node
/**
 * Generates public/able/env-config.js from environment variables.
 * Run automatically via `prebuild` and manually at the start of `dev`.
 *
 * Reads (in priority order):
 *   1. Actual environment variables (CI / GitHub Actions secrets)
 *   2. .env.local  (local overrides — gitignored)
 *   3. .env        (committed defaults)
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

// Simple .env parser (no external dependency needed)
function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return;
  const lines = fs.readFileSync(filePath, "utf8").split("\n");
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eqIdx = trimmed.indexOf("=");
    if (eqIdx < 0) continue;
    const key = trimmed.slice(0, eqIdx).trim();
    const val = trimmed.slice(eqIdx + 1).trim().replace(/^["']|["']$/g, "");
    // Don't overwrite variables already set in the environment (CI takes priority)
    if (!(key in process.env)) process.env[key] = val;
  }
}

// Load .env first, then .env.local on top (local overrides committed defaults)
loadEnvFile(path.join(root, ".env"));
loadEnvFile(path.join(root, ".env.local"));

const hlsBase =
  process.env.ABLE_HLS_BASE ?? "https://stream.dlib.nyu.edu";

const output = `// Auto-generated by scripts/gen-able-config.mjs — do not edit manually.
window.ABLE_ENV = {
  hlsBase: "${hlsBase}",
};
`;

const outPath = path.join(root, "public", "able", "env-config.js");
fs.writeFileSync(outPath, output, "utf8");
console.log(`✓ Generated public/able/env-config.js  (hlsBase: ${hlsBase})`);
